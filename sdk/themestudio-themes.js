// themestudio-themes.js — the built-in Theme Studio catalog. Pure data: every theme is
//   { id, name, desc, colors, appearance, style, sw, sh, widgets }
// where `appearance` drives the live desktop (wallpaper / wallpaperBg / wallpaperFit / motion /
// mode / accent — the same keys Settings → Wallpaper and Appearance write), `style` is the
// widget-identity baseline (the renderer's kind defaults merge under it, instance patches over
// both), and `widgets` is a composition plan in the theme's design space (sw×sh; positions scale
// with the real work area, sizes keep the design). Only wallpapers that exist in the catalog are
// referenced; a theme with no picture uses wallpaperBg (Settings' solid/gradient key).
//
// The catalog's two poles are the user's reference boards: Acid Press (newsprint energy — paper
// cream, ink black, one acid lime, a cobalt media block) and Deep Forest (a serif study in olive
// and cream). Everything else earns its place the same way: a wallpaper that was actually looked
// at, a palette pulled from it, a typographic voice from the eight faces the engine carries, and
// a composition with its own grammar — placement is part of the identity, not an afterthought.

// A plan entry. `o.s` is the style patch, `o.c` the cfg patch; sizes fall back to the kind
// defaults (themestudio-model.TS_KINDS), z is sequential unless spelled out.
const w = (kind, x, y, o = {}) => {
  const e = { kind, x, y };
  if (o.w) e.w = o.w;
  if (o.h) e.h = o.h;
  if (o.z) e.z = o.z;
  if (o.s) e.style = o.s;
  if (o.c) e.cfg = o.c;
  return e;
};

